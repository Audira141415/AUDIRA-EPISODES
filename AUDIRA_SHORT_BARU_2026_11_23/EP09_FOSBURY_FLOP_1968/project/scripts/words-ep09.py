"""public/audio/vo-words.json -> src/scenes/ep09/words.ts (display tokens, numbers as digits, caption chunks)."""
import json
W = json.load(open("public/audio/vo-words.json", encoding="utf8"))
MERGE = {(12, 16): "1968,", (42, 43): "16,", (132, 133): "20", (135, 139): "1968.", (141, 143): "21",
         (146, 149): "2,24", (161, 164): "2,22.", (170, 172): "28", (174, 175): "40", (180, 182): "36",
         (188, 189): "2000,", (190, 192): "34", (206, 206): "AUDIRA", (45, 45): "SMA"}
out, i = [], 0
while i < len(W):
    m = next(((a, b, s) for (a, b), s in MERGE.items() if a == i), None)
    if m:
        a, b, s = m
        out.append({"w": s, "s": W[a]["start"], "e": W[b]["end"]}); i = b + 1
    else:
        out.append({"w": W[i]["text"], "s": W[i]["start"], "e": W[i]["end"]}); i += 1
# caption chunks: break after punctuation or at 4 words
chunks, cur = [], []
for k, w in enumerate(out):
    cur.append(k)
    if w["w"][-1] in ".,?!" and len(cur) >= 2 or len(cur) >= 4 or w["w"][-1] in ".?!":
        chunks.append(cur); cur = []
if cur: chunks.append(cur)
with open("src/scenes/ep09/words.ts", "w", encoding="utf8") as f:
    f.write("// generated by scripts/words-ep09.py from public/audio/vo-words.json\n")
    f.write("export type Word = { w: string; s: number; e: number };\n")
    f.write("export const WORDS: Word[] = " + json.dumps(out, ensure_ascii=False) + ";\n")
    f.write("export const CHUNKS: number[][] = " + json.dumps(chunks) + ";\n")
print(len(out), "display words,", len(chunks), "chunks")
